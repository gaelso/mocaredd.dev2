## ============================================================================
## vendor_flags.R
##
## Self-host the language selector flags in inst/assets/flags/ so the app needs
## no CDN at runtime (offline use).
## Source: flag-icons 6.6.6 (https://github.com/lipis/flag-icons, MIT licence),
## 4x3 flags of the app languages only: gb (en), fr (fr), es (sp).
## Run once from the project root, on a machine with internet access:
##   source("data-raw/vendor_flags.R")
##
## Outputs: inst/assets/flags/<code>.svg, LICENSE.txt and flags.css (the flag-icons
## .fi base rules plus one rule per flag, keeping the classes used in
## R/shiny_run_mocaredd_dev2.R: "fi fi-gb", "fi fi-fr", "fi fi-es").
## ============================================================================

## 1. Configuration ------

flag_version <- "6.6.6"
flag_codes   <- c("gb", "fr", "es")
flag_cdn     <- sprintf("https://cdn.jsdelivr.net/gh/lipis/flag-icons@%s", flag_version)
flag_root    <- "inst/assets/flags"
dir.create(flag_root, showWarnings = FALSE, recursive = TRUE)


## 2. Download flags and licence ------

purrr::walk(flag_codes, \(code) {
  utils::download.file(
    sprintf("%s/flags/4x3/%s.svg", flag_cdn, code),
    file.path(flag_root, paste0(code, ".svg")), mode = "wb", quiet = TRUE
  )
  message(format(Sys.time(), "[%Y-%m-%d %H:%M:%S] "), "Saved ", code, ".svg")
})

utils::download.file(paste0(flag_cdn, "/LICENSE"), file.path(flag_root, "LICENSE.txt"), quiet = TRUE)


## 3. Write flags.css ------

c(
  sprintf("/* flag-icons %s (MIT licence, see LICENSE.txt), app language flags only. */", flag_version),
  "/* Generated by data-raw/vendor_flags.R - do not edit by hand. */",
  ".fi{background-size:contain;background-position:50%;background-repeat:no-repeat;position:relative;display:inline-block;width:1.33333333em;line-height:1em}",
  ".fi:before{content:'\\00a0'}",
  sprintf(".fi-%s{background-image:url(%s.svg)}", flag_codes, flag_codes)
) |>
  writeLines(file.path(flag_root, "flags.css"))

message(
  format(Sys.time(), "[%Y-%m-%d %H:%M:%S] "),
  sprintf("Wrote %s/flags.css and %d flags", flag_root, length(flag_codes))
)
